#!/usr/bin/env python3
"""
Regenerate the fonts bundled with the component (fonts/*.c, include/epd_fonts.h)
and print a Markdown table of their metrics.

    python3 tools/gen_bundled_fonts.py [--inter-dir DIR]

Inter (SIL Open Font License 1.1) is available from https://rsms.me/inter/ or as the
Debian/Ubuntu package fonts-inter.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from fontconvert import convert  # noqa: E402

PIXEL_MM = 0.204   # GDEM075F5x pixel pitch

# (C identifier, file, size, charset, threshold)
FONTS = [
    ("epd_font_inter_regular_12", "Inter-Regular.otf", 12, "cz,arrows", None),
    ("epd_font_inter_regular_16", "Inter-Regular.otf", 16, "cz,arrows", None),
    ("epd_font_inter_regular_20", "Inter-Regular.otf", 20, "cz,arrows", None),
    ("epd_font_inter_regular_24", "Inter-Regular.otf", 24, "cz,arrows", None),
    ("epd_font_inter_regular_32", "Inter-Regular.otf", 32, "cz,arrows", None),
    ("epd_font_inter_bold_16",    "Inter-Bold.otf",    16, "cz,arrows", None),
    ("epd_font_inter_bold_20",    "Inter-Bold.otf",    20, "cz,arrows", None),
    ("epd_font_inter_bold_24",    "Inter-Bold.otf",    24, "cz,arrows", None),
    ("epd_font_inter_bold_32",    "Inter-Bold.otf",    32, "cz,arrows", None),
    ("epd_font_inter_bold_48",    "Inter-Bold.otf",    48, "cz,arrows", None),
    ("epd_font_digits_64",        "InterDisplay-Bold.otf", 64,  "digits", None),
    ("epd_font_digits_96",        "InterDisplay-Bold.otf", 96,  "digits", None),
    ("epd_font_digits_128",       "InterDisplay-Bold.otf", 128, "digits", None),
    ("epd_font_digits_160",       "InterDisplay-Bold.otf", 160, "digits", None),
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--inter-dir", default="/usr/share/fonts/opentype/inter")
    a = ap.parse_args()

    root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    fonts_dir = os.path.join(root, "fonts")
    os.makedirs(fonts_dir, exist_ok=True)

    infos = []
    for ident, file, size, chars, thr in FONTS:
        family = "Inter Display Bold" if "Display" in file else \
                 ("Inter Bold" if "Bold" in file else "Inter Regular")
        src, info = convert(os.path.join(a.inter_dir, file), size, ident, chars, thr,
                            f"{family} {size}")
        with open(os.path.join(fonts_dir, ident + ".c"), "w", encoding="utf-8") as f:
            f.write(src)
        info["chars"] = chars
        infos.append(info)
        if info["missing"]:
            print(f"warning: {ident}: missing {''.join(info['missing'])}", file=sys.stderr)

    hdr = ["/**",
           " * @file epd_fonts.h",
           " * @brief Fonts bundled with the component (Inter, SIL OFL 1.1 - see fonts/LICENSE-Inter.txt).",
           " *",
           " * Generated by tools/gen_bundled_fonts.py. Each font is its own object file, so",
           " * fonts you do not reference are dropped by the linker and cost no flash.",
           " *",
           " * Text fonts contain ASCII, Czech + Slovak letters, ° ± × · – — − … € µ ² ³ ‰ ₀-₉",
           " * and ← ↑ → ↓ ↗ ↘ ▲ ▼ ● ○ ✓ ✗ ⚠. Digit fonts contain only \"0123456789 .,:-+%°/\".",
           " */",
           "#pragma once",
           '#include "epd_font.h"',
           "",
           "#ifdef __cplusplus",
           'extern "C" {',
           "#endif",
           ""]
    for i in infos:
        hdr.append(f"/** {i['name']}: line {i['line_height']} px, caps {i['cap_height']} px "
                   f"({i['cap_height'] * PIXEL_MM:.1f} mm), ~{i['flash_bytes'] / 1024:.1f} kB */")
        hdr.append(f"extern const epd_font_t {i['ident']};")
    hdr += ["", "#ifdef __cplusplus", "}", "#endif", ""]
    with open(os.path.join(root, "include", "epd_fonts.h"), "w", encoding="utf-8") as f:
        f.write("\n".join(hdr))

    print("| Font | Identifier | Line height | Cap height | Cap height on panel | Flash |")
    print("|---|---|---|---|---|---|")
    for i in infos:
        print(f"| {i['name']} | `{i['ident']}` | {i['line_height']} px | {i['cap_height']} px | "
              f"{i['cap_height'] * PIXEL_MM:.1f} mm | {i['flash_bytes'] / 1024:.1f} kB |")
    total = sum(i["flash_bytes"] for i in infos)
    print(f"\nTotal if all fonts are used: {total / 1024:.0f} kB")


if __name__ == "__main__":
    main()
