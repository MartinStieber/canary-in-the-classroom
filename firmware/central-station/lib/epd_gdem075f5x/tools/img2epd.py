#!/usr/bin/env python3
"""
Convert an image (PNG, JPG, ...) into a native 2-bit array for epd_gfx_bitmap2().

    pip install pillow
    python3 img2epd.py logo.png logo -W 200 -o logo.c      # writes logo.c + logo.h

The image is mapped to the four panel colours (black, white, yellow, red), with
Floyd-Steinberg dithering by default. A preview PNG (<output>.preview.png) is written next
to the C file so you can check the result before flashing.

In C:
    #include "logo.h"
    epd_gfx_bitmap2(c, x, y, LOGO_WIDTH, LOGO_HEIGHT, logo, EPD_TRANSPARENT);
"""
import argparse
import os
import re
import sys

from PIL import Image

# index = epd_color_t value
INKS = [(0x22, 0x22, 0x22), (0xFF, 0xFF, 0xFF), (0xE8, 0xC2, 0x1C), (0xB8, 0x2A, 0x2A)]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("image")
    ap.add_argument("ident", help="C identifier of the array")
    ap.add_argument("-W", "--width", type=int, help="resize to this width (keeps aspect ratio)")
    ap.add_argument("-H", "--height", type=int, help="resize to this height (keeps aspect ratio)")
    ap.add_argument("--no-dither", action="store_true", help="nearest colour, no dithering (logos, icons)")
    ap.add_argument("--background", default="ffffff",
                    help="colour used for transparent pixels, hex RRGGBB (default ffffff)")
    ap.add_argument("-o", "--output", help="output .c file (default <ident>.c)")
    a = ap.parse_args()
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", a.ident):
        sys.exit("ident must be a valid C identifier")

    img = Image.open(a.image)
    bg = tuple(int(a.background[i:i + 2], 16) for i in (0, 2, 4))
    if img.mode in ("RGBA", "LA", "P"):
        img = img.convert("RGBA")
        base = Image.new("RGBA", img.size, bg + (255,))
        img = Image.alpha_composite(base, img)
    img = img.convert("RGB")

    if a.width or a.height:
        w, h = img.size
        if a.width and a.height:
            size = (a.width, a.height)
        elif a.width:
            size = (a.width, max(1, round(h * a.width / w)))
        else:
            size = (max(1, round(w * a.height / h)), a.height)
        img = img.resize(size, Image.LANCZOS)
    w, h = img.size
    if w > 800 or h > 800:
        print("warning: image is larger than the panel", file=sys.stderr)

    pal = Image.new("P", (1, 1))
    flat = [v for rgb in INKS for v in rgb]
    pal.putpalette(flat + [0] * (768 - len(flat)))
    q = img.quantize(palette=pal, dither=Image.Dither.NONE if a.no_dither else Image.Dither.FLOYDSTEINBERG)
    px = q.load()

    stride = (w + 3) // 4
    data = []
    for y in range(h):
        row = [0] * stride
        for x in range(w):
            row[x >> 2] |= (px[x, y] & 3) << (6 - 2 * (x & 3))
        data.extend(row)

    out = a.output or f"{a.ident}.c"
    hdr = os.path.splitext(out)[0] + ".h"
    up = a.ident.upper()
    with open(hdr, "w") as f:
        f.write(f"/* Generated by tools/img2epd.py from {os.path.basename(a.image)} */\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define {up}_WIDTH  {w}\n#define {up}_HEIGHT {h}\n\n")
        f.write(f"extern const uint8_t {a.ident}[{len(data)}];\n")
    with open(out, "w") as f:
        f.write(f"/* Generated by tools/img2epd.py from {os.path.basename(a.image)} - "
                f"{w}x{h} px, {len(data)} B */\n")
        f.write(f'#include "{os.path.basename(hdr)}"\n\n')
        f.write(f"const uint8_t {a.ident}[{len(data)}] = {{\n")
        for i in range(0, len(data), 16):
            f.write("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",\n")
        f.write("};\n")

    prev = q.convert("RGB")
    prev.save(os.path.splitext(out)[0] + ".preview.png")
    print(f"{out} + {os.path.basename(hdr)}: {w}x{h} px, {len(data)} B")


if __name__ == "__main__":
    main()
